// PLUGIN INJECTION vs THE LOCK
//
// `flutter pub get` does two jobs: it resolves packages, and it INJECTS plugin scaffolding — the
// generated plugin registrant, the CocoaPods symlinks, and the Swift Package Manager package that
// modern plugins (path_provider_foundation among them) are wired through. Skipping it with --no-pub
// therefore does not merely skip resolution; it leaves the SPM scaffolding stale, and the build dies
// with "Module 'path_provider_foundation' not found" inside GeneratedPluginRegistrant.m.
//
// So injection must run, in the project, with the frontend's Flutter. That rewrites pubspec.lock as a
// side effect — the very thing that must not persist.
//
// The guard below makes that side effect survivable rather than permanent, and it is NOT a naive
// "save, run, restore" (which loses the developer's lock if the process dies in between). The original
// bytes are written to .soroq/ FIRST, and every later run restores from that sidecar before doing
// anything else. A crash at any point leaves the lock recoverable, and the recovery is automatic:
//
//	write sidecar -> pub get (lock rewritten) -> restore from sidecar -> delete sidecar
//	          ^-- a crash anywhere here is repaired by restoreInterruptedLock on the NEXT run
//
// pubspec.yaml is never written at any point; only the lock is ever touched, and only transiently.

// lockGuardPath is where the developer's pubspec.lock is parked for the duration of an injection run.
// It lives under .soroq/ (git-ignored) so the sidecar itself is never a tracked change.
func lockGuardPath(projectDir string) string {
	return filepath.Join(projectDir, ".soroq", "lockguard", "pubspec.lock")
}

// restoreInterruptedLock repairs a lock left rewritten by a run that died before restoring it. It is
// called at the START of every resolution, so recovery needs no developer action and no `git checkout`.
func restoreInterruptedLock(projectDir string) error {
	guard := lockGuardPath(projectDir)
	saved, err := os.ReadFile(guard)
	if err != nil {
		return nil // no interrupted run to repair
	}
	lockPath := filepath.Join(projectDir, "pubspec.lock")
	if current, err := os.ReadFile(lockPath); err == nil && string(current) == string(saved) {
		// Already identical: the previous run restored it but died before clearing the sidecar.
		return os.Remove(guard)
	}
	if err := writeFileAtomic(lockPath, saved); err != nil {
		return fmt.Errorf("restore pubspec.lock after an interrupted Soroq build: %w", err)
	}
	fmt.Fprintf(os.Stderr, "soroq: restored pubspec.lock left rewritten by an interrupted build\n")
	return os.Remove(guard)
}

// runPluginInjection runs the frontend `flutter pub get` in the project so plugin scaffolding (registrant,
// CocoaPods symlinks, SPM package) matches the resolved plugins, then puts pubspec.lock back exactly as
// the developer had it.
func runPluginInjection(projectDir string) error {
	lockPath := filepath.Join(projectDir, "pubspec.lock")
	original, readErr := os.ReadFile(lockPath)
	hadLock := readErr == nil

	if hadLock {
		guard := lockGuardPath(projectDir)
		if err := os.MkdirAll(filepath.Dir(guard), 0o755); err != nil {
			return err
		}
		// Park the original BEFORE anything can rewrite it.
		if err := writeFileAtomic(guard, original); err != nil {
			return fmt.Errorf("park pubspec.lock before dependency injection: %w", err)
		}
	}

	injectErr := runFlutterPubGetIn(projectDir)

	if hadLock {
		if err := writeFileAtomic(lockPath, original); err != nil {
			// Leave the sidecar in place: the next run repairs it.
			return fmt.Errorf("restore pubspec.lock after dependency injection: %w", err)
		}
		if err := os.Remove(lockGuardPath(projectDir)); err != nil && !os.IsNotExist(err) {
			return err
		}
	} else if injectErr == nil {
		// There was no lock before; pub just created one. Removing it keeps the project exactly as the
		// developer left it — their own `pub get` will write the lock they intend to commit.
		_ = os.Remove(lockPath)
	}
	if injectErr != nil {
		return fmt.Errorf("resolve plugin scaffolding: %w", injectErr)
	}
	return nil
}

// pubspecWithAbsolutePathDependencies rewrites every relative `path:` dependency to an absolute path
// anchored at the real project directory.
//
// WHY. The isolated workspace is a temp directory, and the pubspec is copied into it verbatim. A
// relative path dependency — `path: ../../packages/soroq_flutter`, which every monorepo and every
// locally-developed plugin uses — then resolves against the TEMP directory and pub fails with
//
//	Because <app> depends on soroq_flutter from path which doesn't exist
//	(could not find package soroq_flutter at "../../packages/soroq_flutter")
//
// naming a path the developer's own project resolves perfectly well. The isolation is the point of
// the workspace, so the fix is to make the paths location-independent rather than to abandon it.
//
// Absolute paths are only rewritten INTO the workspace copy; the developer's pubspec.yaml on disk is
// never modified.
func pubspecWithAbsolutePathDependencies(text, projectDir string) string {
	lines := strings.Split(text, "\n")
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "path:") {
			continue
		}
		value := strings.TrimSpace(strings.TrimPrefix(trimmed, "path:"))
		// Quoted forms are legal YAML; normalise before deciding, and re-emit unquoted since an
		// absolute POSIX path needs no quoting.
		value = strings.Trim(value, `"'`)
		if value == "" || filepath.IsAbs(value) {
			continue
		}
		indent := line[:len(line)-len(strings.TrimLeft(line, " \t"))]
		lines[i] = indent + "path: " + filepath.Clean(filepath.Join(projectDir, value))
	}
	return strings.Join(lines, "\n")
}
